// Тестовая заглушка статуса занятости — реальных данных о занятости мест
// от партнёров пока нет. Статус детерминированный (от id), чтобы не прыгал
// при каждом рендере, и явно помечен в UI как предварительный.
export function mockAvailability(id) {
  let hash = 0;
  for (let i = 0; i < id.length; i += 1) {
    hash = (hash * 31 + id.charCodeAt(i)) >>> 0;
  }
  const free = hash % 10 !== 0;
  return {
    free,
    label: free ? 'Свободно' : 'Занято',
    note: free
      ? 'Статус предварительный — точную доступность уточняет партнёр при согласовании.'
      : 'Место сейчас занято другим рекламодателем. Уточним у партнёра точные сроки освобождения.',
  };
}
